# 2. Memory layout dictionary — naming consistency with ParameterFlowConfig
# =========================================================================


class TestLayoutDictionaryConsistency:
    """The layout dict keys must match the names generated by ParameterFlowConfig."""

    def _make_tiling(self, spec: Float32ModelSpec) -> TilingScheme:
        return TilingScheme(
            num_module_chunks=(spec.num_modules + 15) // 16,
            num_class_chunks=(spec.output_classes + 15) // 16,
            total_modules=spec.num_modules,
            total_classes=spec.output_classes,
        )

    @pytest.mark.parametrize("batch_size", [32, 150])
    def test_every_flow_buffer_name_exists_in_layouts(self, iris_spec: Float32ModelSpec, batch_size: int) -> None:
        """All non-empty buffer names declared by each flow must be present in the layout dict."""
        ps = ParameterSpace(spec=iris_spec)
        grid = self._make_tiling(iris_spec)
        layouts = ps.get_all_memory_layouts(batch_size=batch_size, grid=grid, num_batch_chunks=4)

        missing = []
        for flow in ps:
            for attr in [
                "param_buffer_name",
                "partial_grad_buffer_name",
                "clipped_partial_grad_buffer_name",
                "summed_grad_buffer_name",
                "final_grad_buffer_name",
                "m1_buffer_name",
                "m2_buffer_name",
            ]:
                name = getattr(flow, attr)
                if name and name not in layouts:
                    missing.append(f"Flow '{flow.name}'.{attr} = '{name}'")

        assert not missing, (
            f"Buffer names declared by ParameterFlowConfig but MISSING in layouts:\n"
            + "\n".join(f"  - {m}" for m in missing)
        )

    def test_clipped_names_match_flow_config_exactly(self, iris_spec: Float32ModelSpec) -> None:
        """
        The `partial_grad_X` → `clipped_partial_grad_X` transform in the layout
        dict must produce keys that exactly match each flow's
        clipped_partial_grad_buffer_name.

        Regression: a prior bug used .replace("partial", "clipped") which
        turned 'partial_grad_X' into 'clipped_grad_X' — missing the 'partial'.
        """
        ps = ParameterSpace(spec=iris_spec)
        grid = self._make_tiling(iris_spec)
        layouts = ps.get_all_memory_layouts(batch_size=150, grid=grid, num_batch_chunks=4)

        for flow in ps:
            if not flow.clipped_partial_grad_buffer_name:
                continue
            expected_name = flow.clipped_partial_grad_buffer_name
            assert expected_name in layouts, (
                f"Flow '{flow.name}': expected layout key '{expected_name}' "
                f"but it is ABSENT.  Layout keys containing 'clipped': "
                f"{[k for k in layouts if 'clipped' in k]}"
            )

    def test_partial_and_clipped_shapes_match(self, iris_spec: Float32ModelSpec) -> None:
        """A clipped buffer must have exactly the same logical shape as its partial precursor."""
        ps = ParameterSpace(spec=iris_spec)
        grid = self._make_tiling(iris_spec)
        layouts = ps.get_all_memory_layouts(batch_size=150, grid=grid, num_batch_chunks=4)

        for flow in ps:
            if not flow.partial_grad_buffer_name or not flow.clipped_partial_grad_buffer_name:
                continue
            partial_layout = layouts[flow.partial_grad_buffer_name]
            clipped_layout = layouts[flow.clipped_partial_grad_buffer_name]
            assert partial_layout.logical_shape == clipped_layout.logical_shape, (
                f"Flow '{flow.name}': partial shape {partial_layout.logical_shape} "
                f"!= clipped shape {clipped_layout.logical_shape}"
            )


