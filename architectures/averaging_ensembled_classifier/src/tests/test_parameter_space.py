# src/tests/test_parameter_space.py
"""
Unit tests for ParameterSpace: flow declarations, naming conventions,
and memory layout generation.

Bug-hunting focus:
* The "partial_grad" → "clipped_partial_grad" naming transform must be
  consistent between ParameterFlowConfig.clipped_partial_grad_buffer_name
  and the layout dictionary entry generated by get_all_memory_layouts().
* Every flow's buffer names must actually appear in the layout dict.
* Hidden_activations flow (specialized_reduction=True) must NOT create
  layout entries for partial/clipped/final/adam buffers.
"""
from __future__ import annotations

import numpy as np
import pytest

from src.model_spec import Float32ModelSpec, Float16ModelSpec
from src.parameter_space import ParameterSpace, ParameterFlowConfig
from src.workload_primitives import TilingScheme


# =========================================================================
# 1. ParameterFlowConfig naming consistency
# =========================================================================


class TestParameterFlowConfigNaming:
    """Each flow must generate buffer names following a predictable pattern."""

    def test_standard_flow_names(self) -> None:
        """A non-specialized flow should produce six distinct buffer name fields."""
        ps = ParameterSpace(spec=Float32ModelSpec(
            input_dim=4, hidden_dim=32, output_classes=3,
            num_modules=8, simd_width=4, cache_line_bytes=64,
        ))
        standard_flows = [f for f in ps if not f.specialized_reduction]
        assert len(standard_flows) >= 4, "Expected at least shared_weights, shared_biases, module_weights, module_biases"

        for flow in standard_flows:
            # partial must contain "partial_grad"
            assert "partial_grad" in flow.partial_grad_buffer_name, \
                f"Flow '{flow.name}': partial_grad_buffer_name = '{flow.partial_grad_buffer_name}' lacks 'partial_grad'"
            # clipped must contain "clipped_partial_grad"
            assert "clipped_partial_grad" in flow.clipped_partial_grad_buffer_name, \
                f"Flow '{flow.name}': clipped name = '{flow.clipped_partial_grad_buffer_name}' lacks 'clipped_partial_grad'"
            # summed
            assert flow.summed_grad_buffer_name.startswith("summed_grad_"), \
                f"Flow '{flow.name}': summed = '{flow.summed_grad_buffer_name}'"
            # final
            assert flow.final_grad_buffer_name.startswith("final_grad_"), \
                f"Flow '{flow.name}': final = '{flow.final_grad_buffer_name}'"
            # adam
            assert flow.m1_buffer_name.startswith("m1_"), \
                f"Flow '{flow.name}': m1 = '{flow.m1_buffer_name}'"
            assert flow.m2_buffer_name.startswith("m2_"), \
                f"Flow '{flow.name}': m2 = '{flow.m2_buffer_name}'"

    def test_specialized_flow_has_empty_buffer_names(self) -> None:
        """The hidden_activations flow is specialized and should not have intermediate buffer names."""
        ps = ParameterSpace(spec=Float32ModelSpec(
            input_dim=4, hidden_dim=32, output_classes=3,
            num_modules=8, simd_width=4, cache_line_bytes=64,
        ))
        specialized = [f for f in ps if f.specialized_reduction]
        assert len(specialized) >= 1
        for flow in specialized:
            assert flow.partial_grad_buffer_name == "", f"Expected empty partial for specialized flow '{flow.name}'"
            assert flow.clipped_partial_grad_buffer_name == ""
            assert flow.final_grad_buffer_name == ""
            assert flow.m1_buffer_name == ""
            assert flow.m2_buffer_name == ""
            # But summed should exist
            assert flow.summed_grad_buffer_name != ""

    def test_temperatures_use_temps_grad_name(self) -> None:
        """The temperatures flow uses 'temps' as the grad name, not 'temperatures'."""
        ps = ParameterSpace(spec=Float32ModelSpec(
            input_dim=4, hidden_dim=32, output_classes=3,
            num_modules=8, simd_width=4, cache_line_bytes=64,
        ))
        temp_flow = next(f for f in ps if f.name == "temperatures")
        assert temp_flow.partial_grad_buffer_name == "partial_grad_temps"
        assert temp_flow.clipped_partial_grad_buffer_name == "clipped_partial_grad_temps"
        assert temp_flow.summed_grad_buffer_name == "summed_grad_temps"


