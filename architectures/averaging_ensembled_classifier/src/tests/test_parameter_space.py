# 3. Memory layout shapes — dimensionality correctness
# =========================================================================


class TestLayoutShapes:
    """Verify that critical layout shapes are dimensionally self-consistent."""

    def _make_layouts(self, spec, batch_size=150, num_batch_chunks=4):
        ps = ParameterSpace(spec=spec)
        grid = TilingScheme(
            num_module_chunks=(spec.num_modules + 15) // 16,
            num_class_chunks=(spec.output_classes + 15) // 16,
            total_modules=spec.num_modules,
            total_classes=spec.output_classes,
        )
        return ps.get_all_memory_layouts(batch_size=batch_size, grid=grid, num_batch_chunks=num_batch_chunks), grid

    def test_shared_weights_shape(self, iris_spec: Float32ModelSpec) -> None:
        """shared_weights shape must be (padded_hidden_dim, padded_input_dim)."""
        layouts, _ = self._make_layouts(iris_spec)
        sw = layouts["shared_weights"]
        assert sw.logical_shape == (iris_spec.padded_hidden_dim, iris_spec.padded_input_dim)

    def test_module_weights_shape(self, iris_spec: Float32ModelSpec) -> None:
        """module_weights shape must be (num_modules, padded_hidden_dim, padded_class_dim)."""
        layouts, _ = self._make_layouts(iris_spec)
        mw = layouts["module_weights"]
        assert mw.logical_shape == (
            iris_spec.num_modules,
            iris_spec.padded_hidden_dim,
            iris_spec.padded_class_dim,
        )

    def test_adam_state_shapes_match_params(self, iris_spec: Float32ModelSpec) -> None:
        """Optimizer state buffers (m1, m2, summed_grad, final_grad) match the param shape."""
        layouts, _ = self._make_layouts(iris_spec)
        ps = ParameterSpace(spec=iris_spec)

        for flow in ps:
            if flow.specialized_reduction:
                continue
            param_shape = layouts[flow.param_buffer_name].logical_shape
            for buf_name in [flow.summed_grad_buffer_name, flow.final_grad_buffer_name,
                             flow.m1_buffer_name, flow.m2_buffer_name]:
                assert layouts[buf_name].logical_shape == param_shape, (
                    f"Flow '{flow.name}': '{buf_name}' shape {layouts[buf_name].logical_shape} "
                    f"!= param shape {param_shape}"
                )

    def test_partial_grad_module_weights_has_tile_dim(self, iris_spec: Float32ModelSpec) -> None:
        """partial_grad_module_weights must have a leading tile dimension."""
        layouts, grid = self._make_layouts(iris_spec)
        pgmw = layouts["partial_grad_module_weights"]
        assert pgmw.logical_shape[0] == grid.total_tiles, (
            f"First dim {pgmw.logical_shape[0]} != total_tiles {grid.total_tiles}"
        )

    def test_partial_grad_shared_weights_has_chunk_dim(self, iris_spec: Float32ModelSpec) -> None:
        """partial_grad_shared_weights must have a leading batch-chunk dimension."""
        layouts, _ = self._make_layouts(iris_spec, num_batch_chunks=4)
        pgsw = layouts["partial_grad_shared_weights"]
        assert pgsw.logical_shape[0] == 4, f"First dim {pgsw.logical_shape[0]} != num_batch_chunks=4"
        assert pgsw.logical_shape[1] == iris_spec.padded_hidden_dim
        assert pgsw.logical_shape[2] == iris_spec.padded_input_dim

    @pytest.mark.parametrize("spec_name", ["iris", "hydra", "lexicon"])
    def test_final_probs_exists(self, spec_name, iris_spec, hydra_spec, lexicon_spec) -> None:
        """final_probs must be present as a layout key."""
        specs = {"iris": iris_spec, "hydra": hydra_spec, "lexicon": lexicon_spec}
        layouts, _ = self._make_layouts(specs[spec_name])
        assert "final_probs" in layouts, f"'final_probs' missing from layout dict for {spec_name}"

    def test_final_loss_exists(self, iris_spec: Float32ModelSpec) -> None:
        """final_loss must be present as a layout key."""
        layouts, _ = self._make_layouts(iris_spec)
        assert "final_loss" in layouts

    def test_permuted_grad_h_shape(self, iris_spec: Float32ModelSpec) -> None:
        """permuted_grad_h must be (batch*padded_hidden, padded_module_dim)."""
        layouts, _ = self._make_layouts(iris_spec)
        p = layouts["permuted_grad_h"]
        assert p.logical_shape == (
            150 * iris_spec.padded_hidden_dim,
            iris_spec.padded_module_dim,
        )


