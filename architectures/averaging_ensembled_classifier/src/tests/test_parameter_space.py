class TestStressScenarios:
    """Verify that large-scale configs don't break naming or shape contracts."""

    @pytest.mark.parametrize("spec_fixture,batch_size", [
        ("hydra_spec", 32),
        ("lexicon_spec", 64),
    ])
    def test_all_flow_names_in_layouts(self, spec_fixture, batch_size, request) -> None:
        spec = request.getfixturevalue(spec_fixture)
        ps = ParameterSpace(spec=spec)
        grid = TilingScheme(
            num_module_chunks=(spec.num_modules + 15) // 16,
            num_class_chunks=(spec.output_classes + 15) // 16,
            total_modules=spec.num_modules,
            total_classes=spec.output_classes,
        )
        layouts = ps.get_all_memory_layouts(batch_size=batch_size, grid=grid, num_batch_chunks=4)

        for flow in ps:
            for attr in [
                "param_buffer_name",
                "partial_grad_buffer_name",
                "clipped_partial_grad_buffer_name",
                "summed_grad_buffer_name",
                "final_grad_buffer_name",
                "m1_buffer_name",
                "m2_buffer_name",
            ]:
                name = getattr(flow, attr)
                if name:
                    assert name in layouts, f"Missing layout for {spec_fixture} flow '{flow.name}'.{attr} = '{name}'"
